def route(question, facts, history=None):
    """→ (режим, причина) для готового шаблона, или (None, None) — идти в поиск по базе знаний."""
    q = question or ""
    r = urgent_reason(q, facts, history)
    if r:
        return "urgent", r
    plain = kk_norm(q)
    if F.is_child(facts) or _any(CHILD_Q, q) or _any(KK_RULES["child"], plain):
        return "child", None
    if GREETING.search(q):
        return "answer", "greeting"
    if THANKS.search(q):
        return "answer", "thanks"
    if ABOUT.search(q):
        return "answer", "about"
    if _any(PRICE, q):
        return "dont_know", "price"
    if _any(PAST, q):
        return "dont_know", "past"
    if _any(CERT, q):
        return "answer", "certificate"
    if _any(DOSE, q) or _any(KK_RULES["dose"], plain):
        return "answer", "dose"
    if _any(DRUG, q) or _any(KK_RULES["drug"], plain):
        return "answer", "drug"
    if _any(DIAGNOSIS, q) or _any(KK_RULES["diagnosis"], plain):
        return "answer", "diagnosis"
    if F.GLYCATED.search(q) or (
        OTHER_ANALYTE.search(q)
        and not ANEMIA_WORD.search(q)
        and not ANEMIA_CONTEXT.search(q)
    ):  # гликированный гемоглобин (HbA1c) — анализ на сахар, не на анемию
        return "out_of_scope", "other_analyte"
    kk_topic = lang_of(q) == "kk" and KK_DOMAIN.search(plain)
    if q and not DOMAIN.search(q) and not kk_topic and not F.hb_from_question(q, facts):
        if len(LATIN.findall(q)) > len(CYR_KK.findall(q)):
            return "answer", "language"
        return "out_of_scope", None
    return None, None


def needs_retake(question, facts):
    """Снимок непригоден, анализа нет, в вопросе нет числа Hb → на вопросы о результате «переснимите»."""
    ph = facts.get("photo")
    return (
        bool(ph)
        and ph.get("status") != "ok"
        and not facts.get("lab")
        and not F.hb_from_question(question, facts)
    )
