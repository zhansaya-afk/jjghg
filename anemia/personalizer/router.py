def lang_of(question):
    """kk — если ≥2 казахских букв или 1 буква и казахские слова («бола ма», «керек»): буквы есть не в каждом слове."""
    q = question or ""
    n = len(KK_LETTERS.findall(q))
    return (
        "kk"
        if n >= 2 or (n >= 1 and KK_WORDS.search(q)) or len(KK_WORDS.findall(q)) >= 2
        else "ru"
    )


def urgent_reason(question, facts, history=None):
    """Причина срочности или None. Смотрит вопрос, реплики пользователя в истории, опрос и тяжёлый Hb."""
    texts = [question or ""] + [
        h.get("text", "") for h in (history or [])[-4:] if h.get("role") == "user"
    ]
    for t in texts:
        for reason, rxs in URGENT.items():
            if _any(rxs, t):
                if reason == "dizzy" and not (
                    F.is_pregnant(facts)
                    or "беремен" in t.lower()
                    or "сильно" in t.lower()
                ):
                    continue
                return reason
    if F.survey_flag(facts, "red_flag"):
        return "survey"
    lab = facts.get("lab")
    if lab and lab.get("grade") == "severe":
        return "lab"
    return None


def route(question, facts, history=None):
    """→ (режим, причина) для готового шаблона, или (None, None) — идти в поиск по базе знаний."""
    q = question or ""
    r = urgent_reason(q, facts, history)
    if r:
        return "urgent", r
    if F.is_child(facts) or _any(CHILD_Q, q):
        return "child", None
    if GREETING.search(q):
        return "answer", "greeting"
    if THANKS.search(q):
        return "answer", "thanks"
    if ABOUT.search(q):
        return "answer", "about"
    if _any(PRICE, q):
        return "dont_know", "price"
    if _any(PAST, q):
        return "dont_know", "past"
    if _any(CERT, q):
        return "answer", "certificate"
    if _any(DOSE, q):
        return "answer", "dose"
    if _any(DRUG, q):
        return "answer", "drug"
    if _any(DIAGNOSIS, q):
        return "answer", "diagnosis"
    if q and not DOMAIN.search(q) and not F.hb_from_question(q, facts):
        if len(LATIN.findall(q)) > len(CYR_KK.findall(q)):
            return "answer", "language"
        return "out_of_scope", None
    return None, None


def needs_retake(question, facts):
    """Снимок непригоден, анализа нет, в вопросе нет числа Hb → на вопросы о результате «переснимите»."""
    ph = facts.get("photo")
    return (
        bool(ph)
        and ph.get("status") != "ok"
        and not facts.get("lab")
        and not F.hb_from_question(question, facts)
    )
