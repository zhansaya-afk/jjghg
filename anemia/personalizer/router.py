def kk_norm(text):
    """Казахские буквы → похожие русские (ә→а, қ→к, ұ/ү→у, і→и …), нижний регистр."""
    t = (text or "").translate(_KK_PLAIN).lower().replace("ё", "е")
    return re.sub(r"(?<=[а-я])i|i(?=[а-я])", "и", t)  # «есiмнен» с латинской i


