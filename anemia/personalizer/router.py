def lang_of(question):
    """kk — если ≥2 казахских букв или 1 буква и казахские слова («бола ма», «керек»): буквы есть не в каждом слове."""
    q = question or ""
    n = len(KK_LETTERS.findall(q))
    plain = len(KK_WORDS_PLAIN.findall(kk_norm(q)))
    return (
        "kk"
        if n >= 2
        or (n >= 1 and (KK_WORDS.search(q) or plain))
        or len(KK_WORDS.findall(q)) >= 2
        or plain >= 2
        else "ru"
    )


def urgent_reason(question, facts, history=None):
    """Причина срочности или None. Смотрит вопрос, реплики пользователя в истории, опрос и тяжёлый Hb."""
    texts = [question or ""] + [
        h.get("text", "") for h in (history or [])[-4:] if h.get("role") == "user"
    ]
    for t in texts:
        plain = kk_norm(t)
        for reason, rxs in URGENT.items():
            if _any(rxs, t) or _any(KK_URGENT.get(reason, ()), plain):
                if (
                    reason == "bleeding"
                    and "етеккир" in plain
                    and not re.search(r"катты|токтамай|жукти|кансыра", plain)
                ):
                    continue  # «во время месячных идёт кровь» — обильные месячные, не кровотечение
                if reason == "dizzy" and not (
                    F.is_pregnant(facts)
                    or re.search(r"беремен|сильно|жукти|катты|\bоте\b", plain)
                ):
                    continue
                return reason
    if F.survey_flag(facts, "red_flag"):
        return "survey"
    lab = facts.get("lab")
    if lab and lab.get("grade") == "severe":
        return "lab"
    return None


