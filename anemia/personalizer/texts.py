"""Фразы персонализатора, собранные из карточки фактов («слоты»), и готовые шаблоны режимов.

Каждая фраза берёт цифры только из карточки фактов или из вопроса. Уровень риска называет только
photo_line / risk_meaning (по факту из фото), норму ВОЗ — только lab_line / norm_line (по профилю).
Казахские тексты — черновик: их должен проверить носитель языка.
"""

import re

from . import facts as F

GRADE_WORD = {"mild": "лёгкая", "moderate": "умеренная", "severe": "тяжёлая"}
RISK_KK = {"низкий": "төмен", "средний": "орташа", "высокий": "жоғары"}


def join(*parts):
    return " ".join(p.strip() for p in parts if p and p.strip())


def _hb(v):
    return f"{float(v):.0f}"


# ------------------------------------------------------------------ слоты (ru)
def doctor(f):
    """Кому показать (дательный падеж)."""
    return (
        "врачу, который ведёт беременность" if F.is_pregnant(f) else "врачу-терапевту"
    )


def photo_line(f):
    ph = f.get("photo")
    if not ph or F.is_child(f):
        return ""
    if ph.get("status") == "ok":
        reason = (ph.get("reason") or "").strip().rstrip(".")
        return f"По фото риск анемии {ph['risk']}" + (
            f" ({reason})." if reason else "."
        )
    if ph.get("stage") == "ood" or (
        ph.get("status") == "unreliable" and not ph.get("reason")
    ):
        return "Фото оценить нельзя: снимок не похож на те, на которых училась система."
    return (
        f"Фото оценить нельзя: {(ph.get('reason') or 'снимок не подошёл').rstrip('.')}."
    )


def risk_meaning(f):
    if not F.photo_ok(f):
        return ""
    return {
        "высокий": "Высокий риск значит, что веко на фото бледнее обычного: у людей с похожими снимками "
        "гемоглобин чаще оказывался ниже нормы.",
        "средний": "Средний риск значит, что по фото нельзя уверенно сказать ни «похоже на норму», "
        "ни «похоже на анемию».",
        "низкий": "Низкий риск значит, что бледности на фото не видно, но анемию это не исключает: "
        "метод может ошибаться, особенно при лёгкой анемии.",
    }.get(f["photo"].get("risk"), "")


def hb_photo(f):
    if not F.photo_ok(f):
        return ""
    iv = f["photo"].get("hb_interval_g_l")
    if iv:
        return (
            f"Ориентировочно гемоглобин {_hb(iv[0])}–{_hb(iv[1])} г/л, но это примерная оценка по цвету века, "
            "а не измерение."
        )
    return "Цифру гемоглобина по этому фото система не даёт: такая оценка была бы ненадёжной."


def norm_line(f, question=""):
    """Норма для профиля; если вопрос про другую группу — её порог отдельным предложением (без слова «норма»,
    чтобы первой нормой в ответе всегда была норма профиля)."""
    return join(
        f"Для {F.group_name(f)} норма ВОЗ — от {F.norm_g_l(f)} г/л.",
        other_groups(f, question),
    )


def other_groups(f, question="", hb=None):
    """Вопрос про другую группу («а для мужчин?») → её порог ВОЗ; hb — сравнить число из вопроса с ним."""
    q, p = (question or "").lower(), f.get("profile") or {}
    out = []

    def add(text, thr):
        cmp = ""
        if hb is not None:
            cmp = f" {_hb(hb)} г/л " + (
                "ниже этого порога." if hb < thr else "не ниже этого порога."
            )
        out.append(text + cmp)

    if re.search(r"мужчин|\bмуж\b|мужик|парн", q) and p.get("sex") != "M":
        add("Для мужчин порог ВОЗ выше — 130 г/л.", 130)
        out.append(
            "Ответ дан по полу из вашего профиля; если он указан неверно, исправьте его."
        )
    elif re.search(r"женщин|девушк", q) and p.get("sex") != "F":
        add("Для женщин порог ВОЗ — 120 г/л.", 120)
        out.append(
            "Ответ дан по полу из вашего профиля; если он указан неверно, исправьте его."
        )
    if "беремен" in q and not F.is_pregnant(f) and p.get("sex") != "M":
        add("При беременности порог ВОЗ — 110 г/л.", 110)
    return join(*out)


def _lab_sentence(hb, grade, f, prefix=""):
    group, norm = F.group_name(f), F.norm_g_l(f)
    if grade == "norm":
        s = f"{prefix}{_hb(hb)} г/л — в пределах нормы ВОЗ для {group} (от {norm} г/л)"
        sex = (f.get("profile") or {}).get("sex")
        if hb > (160 if sex == "F" else 170):
            return (
                s
                + ", но выше обычных значений: повышенный гемоглобин тоже стоит показать врачу."
            )
        return s + (", но близко к нижней границе." if hb < norm + 5 else ".")
    return f"{prefix}{_hb(hb)} г/л — ниже нормы ВОЗ для {group} (от {norm} г/л), по критериям ВОЗ это {GRADE_WORD[grade]} степень."


def lab_line(f, question=""):
    """Анализ из карточки; если его нет — число из вопроса (с пересчётом г/дл)."""
    lab = f.get("lab")
    unit = ""
    q = F.hb_from_question(question, f)
    if lab:
        mine = _lab_sentence(lab["hb_g_l"], lab["grade"], f, "Анализ крови: ")
        if q and abs(q[0] - lab["hb_g_l"]) < 1:
            if q[1] != "г/л":
                unit = f"{question_number(question)} {q[1]} = {_hb(lab['hb_g_l'])} г/л ({_HOW[q[1]]})."
            return join(unit, mine)
        if (
            q
        ):  # в вопросе другое число: ответить про него и напомнить анализ из карточки
            return join(
                _question_sentence(q, f, question),
                "В вашем анализе в приложении: " + mine[len("Анализ крови: ") :],
            )
        return mine
    if q:
        return _question_sentence(q, f, question)
    return ""


_HOW = {"г/дл": "умножьте на 10", "ммоль/л": "умножьте ммоль/л примерно на 16"}
_MMOL_NOTE = (
    " Пересчёт в г/л: умножьте ммоль/л примерно на 16. В ммоль/л гемоглобин пишут редко, чаще так пишут глюкозу: "
    "убедитесь, что это строка HGB (гемоглобин)."
)


def _question_sentence(q, f, question):
    hb, unit = q
    prefix = (
        "Если это гемоглобин в г/л, то "
        if unit == "г/л"
        else f"Если это {question_number(question)} {unit}, то это "
    )
    s = _lab_sentence(hb, F.grade_of(hb, f), f, prefix) + (
        ""
        if unit == "г/л"
        else " Проверьте единицы на бланке." + (_MMOL_NOTE if unit == "ммоль/л" else "")
    )
    return join(s, other_groups(f, question, hb))


def question_number(question):
    m = F._NUM.search(question or "")
    return m.group(0) if m else ""


def lab_grade(f, question=""):
    if f.get("lab"):
        return f["lab"]["grade"]
    q = F.hb_from_question(question, f)
    return F.grade_of(q[0], f) if q else None


def lab_advice(f, question=""):
    g = lab_grade(f, question)
    if g is None:
        return ""
    if g == "norm":
        return (
            "Если при этом есть слабость или выпадение волос, спросите врача о ферритине: запасы железа "
            "могут быть низкими и при нормальном гемоглобине."
        )
    return (
        f"Причину и диагноз определяет врач: чаще всего проверяют ферритин (запасы железа). Покажите анализ "
        f"{doctor(f)} в ближайшие дни."
    )


def lab_vs_photo(f, question=""):
    """Фото и анализ (из карточки или число из вопроса): чему верить и почему они могут расходиться."""
    g = lab_grade(f, question)
    if g is None or not F.photo_ok(f):
        return ""
    s = "Анализ крови точнее, чем оценка по фото, поэтому ориентируйтесь на анализ: оценка по фото — только скрининг, не диагноз."
    risk, anemic = f["photo"]["risk"], g != "norm"
    if (risk == "высокий" and not anemic) or (risk == "низкий" and anemic):
        s += " Фото может ошибаться: давать ложную тревогу (например, из-за света) или пропускать анемию."
    return s


def lab_missing(f, question=""):
    if F.photo_ok(f) and not f.get("lab") and not F.hb_from_question(question, f):
        return "Анализа крови в приложении нет: если вы его сдали, введите гемоглобин — анализ точнее фото."
    return ""


def tissue_line(f):
    if not F.photo_ok(f):
        return ""
    t = f["photo"].get("tissue")
    if t == "склера":
        return (
            "На снимке не было видно внутренней стороны нижнего века (конъюнктивы), поэтому оценка сделана "
            "по склере, белку глаза. Она менее надёжна. Лучше переснимите: оттяните нижнее веко пальцем, чтобы "
            "была видна розовая полоска, и снимайте при дневном свете."
        )
    if t == "обе":
        return "Оценка сделана по конъюнктиве (внутренней стороне нижнего века) и по склере вместе."
    return "Оценка сделана по конъюнктиве — внутренней стороне нижнего века: её цвет лучше всего отражает гемоглобин."


_GROUP_Q = (
    (r"женщин|девуш", "женщин"),
    (r"мужчин|\bмуж\b|мужик|парн", "мужчин"),
    (r"беремен", "беременных"),
    (r"\bдет|реб[её]н|подрост|школьн|\bмне\s+1\d\s*(?:лет|год)", "детей и подростков"),
    (r"пожил|стар(?:ик|ше|ых|ый)|\bмне\s+[6-9]\d\s*(?:лет|год)", "пожилых"),
)


def accuracy(f, question=""):
    v = ((f.get("photo") or {}).get("validation")) or F.MODEL_CARD
    q = (question or "").lower()
    group = next((name for rx, name in _GROUP_Q if re.search(rx, q)), None)
    note = ""
    if group in ("детей и подростков", "беременных"):
        note = f"Для {group} точность не проверяли: их в проверке не было, поэтому ориентируйтесь на анализ крови."
    elif group:
        note = f"Отдельно для {group} точность не считали: людей в проверке слишком мало, цифры выше — для всех вместе."
    return join(
        f"Честно: на проверке у {v['patients']} взрослых система находила {v['sensitivity_pct']}% людей с анемией "
        f"и правильно отмечала {v['specificity_pct']}% людей без неё. Значит, она может ошибиться в обе стороны: "
        "пропустить анемию или поднять ложную тревогу.",
        note,
        "Снимки были с насадки, на обычном телефоне точность может быть ниже. Это скрининг, не диагноз: точный "
        "ответ даст общий анализ крови.",
    )


def dataset_line(f):
    v = ((f.get("photo") or {}).get("validation")) or F.MODEL_CARD
    with_anemia = (
        f", из них {v['anemic']} с анемией по критериям ВОЗ" if v.get("anemic") else ""
    )
    return (
        f"Систему проверяли на {v['patients']} взрослых{with_anemia}: открытый набор Eyes-defy (Италия и Индия, "
        "снимки века с насадки, у каждого измерен гемоглобин). Проверка шла на людях, которых модель не видела при "
        f"обучении. Из людей с анемией система находила {v['sensitivity_pct']}%, без анемии правильно отмечала "
        f"{v['specificity_pct']}%. Детей, подростков и беременных в проверке не было, снимков обычным телефоном "
        "тоже. Это скрининг, не диагноз."
    )


def probability(f):
    if not F.photo_ok(f) or f["photo"].get("p_anemia") is None:
        return "По этому снимку вероятность не рассчитана. Проверить можно только общим анализом крови."
    p = f["photo"]["p_anemia"]
    return (
        f"Вероятность {round(100 * p)}% — это оценка модели: среди людей с похожим по цвету снимком примерно у "
        f"{round(10 * p)} из 10 гемоглобин оказывался ниже нормы. Это не означает, что у вас точно анемия: это "
        "скрининг. Проверить можно только общим анализом крови."
    )


def is_vegan(f, question=""):
    q = (question or "").lower()
    # «я не вегетарианка» — не про веганство; сказанное о себе уже учтено в опросе (context.dialog_facts)
    return F.survey_no(f, "meat_fish") or bool(
        re.search(r"(?<!не )(?:веган|вегетариан)", q)
    )


def tests(f, question=""):
    items = ["общий анализ крови (ОАК) с MCV", "ферритин (запасы железа)"]
    if is_vegan(f, question):
        items.append("витамин B12 и фолиевую кислоту")
    if F.survey_flag(f, "family_thalassemia"):
        items.append("электрофорез гемоглобина")
    s = (
        "Обычно начинают с таких анализов: "
        + ", ".join(items)
        + ". Окончательный список определяет врач."
    )
    q = (question or "").lower()
    if F.survey_flag(f, "heavy_periods") or "месячн" in q:
        s += " При обильных месячных полезно показаться гинекологу."
    return s


def _gi_relevant(f):
    p = f.get("profile") or {}
    adult = p.get("age") is None or p["age"] >= 18
    older_f = p.get("sex") == "F" and p.get("age") is not None and p["age"] >= 50
    concern = (F.photo_ok(f) and f["photo"]["risk"] in ("средний", "высокий")) or (
        f.get("lab") and f["lab"]["grade"] != "norm"
    )
    return (
        adult and concern and (p.get("sex") == "M" or older_f) and not F.is_pregnant(f)
    )


def survey_hints(f, question=""):
    out = []
    q = (question or "").lower()
    if F.survey_flag(f, "heavy_periods") or "месячн" in q:
        out.append(
            "Одна из частых возможных причин у женщин — обильные месячные: с ними теряется железо."
        )
    if is_vegan(f, question):
        out.append("Без мяса и рыбы чаще не хватает железа и витамина B12.")
    if F.survey_flag(f, "donor") or "донор" in q:
        out.append(
            "При частой сдаче крови запасы железа не всегда успевают восстановиться."
        )
    if F.survey_flag(f, "family_thalassemia"):
        out.append(
            "Талассемия наследственная и тоже снижает гемоглобин, но лечится не так, как нехватка железа, "
            "поэтому не стоит самостоятельно принимать железо."
        )
    cd = (f.get("survey") or {}).get("chronic_disease")
    if isinstance(cd, str) and "почк" in cd.lower():
        out.append(
            "Почки вырабатывают гормон эритропоэтин, нужный для образования эритроцитов; обсудите это с нефрологом."
        )
    if _gi_relevant(f):
        out.append(
            "У мужчин и у женщин после менопаузы при нормальном питании частая возможная причина — скрытая "
            "кровопотеря из желудка или кишечника, поэтому важно пройти обследование у врача."
        )
    return join(*out)


def next_step(f):
    if f.get("lab"):
        return f"Покажите анализ {doctor(f)}."
    if F.photo_ok(f):
        return f"Сдайте общий анализ крови в ближайшие дни и покажите результат {doctor(f)}."
    return ""


def test_need(f, question=""):
    concern = (F.photo_ok(f) and f["photo"]["risk"] in ("средний", "высокий")) or (
        f.get("lab") and f["lab"]["grade"] != "norm"
    )
    if concern:
        return join(
            photo_line(f), "Да, стоит: сдайте общий анализ крови в ближайшие дни."
        )
    return (
        "Срочности нет: общий анализ крови можно сдать при плановом осмотре. Низкий риск по фото анемию не "
        "исключает: метод может ошибаться. Если появятся слабость, одышка, головокружение или бледность, сдайте "
        "общий анализ крови раньше и покажите врачу."
    )


