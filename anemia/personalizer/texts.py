def urgent(f, reason):
    if reason == "crisis":
        return CRISIS
    if reason == "lab":
        lab = f["lab"]
        first = f"{_hb(lab['hb_g_l'])} г/л — очень низкий гемоглобин, по ВОЗ тяжёлая степень."
    else:
        first = URGENT_REASON.get(reason, "Это опасный признак.")
    who = (
        "свяжитесь с врачом, который ведёт беременность, или "
        if F.is_pregnant(f)
        else "обратитесь к врачу или "
    )
    return join(
        first,
        f"Не ждите: сегодня же {who}вызовите скорую помощь — 103 или 112, если состояние ухудшается.",
        "Остальные вопросы — после осмотра врача.",
    )


