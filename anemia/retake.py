"""Понятные подсказки «переснимите, потому что …» по результату analyze_photo (2026-11-18).

Проверки качества пишут технические строки (`issues`: «снимок размыт (резкость 1.21 < 1.3 …)»). Здесь они
сводятся к коротким причинам для человека: что не так и что сделать. Только текст: на решение (статус, стадия,
риск) модуль не влияет. Функции чистые: dict результата / строки на входе, строки на выходе.
"""
import re

# (код, шаблон по тексту проблемы, «потому что …», «что сделать»). Порядок = приоритет показа.
RULES = (
    ('frame_small', r'изображение слишком маленькое',
     'изображение слишком маленькое', 'пришлите оригинал фото из камеры, не миниатюру и не скриншот'),
    ('no_color', r'без цвета',
     'снимок почти без цвета (чёрно-белый, фильтр или сильный пересвет)',
     'выключите фильтры и вспышку, снимите обычной камерой'),
    ('dark', r'почти чёрный|слишком темно',
     'слишком темно — цвет века не различить', 'включите верхний свет или встаньте у окна; вспышку не включайте'),
    ('overexposed', r'пересвет|вспышк',
     'пересвет или блик: на веке белое пятно, цвет ткани потерян',
     'выключите вспышку и повернитесь так, чтобы лампа или окно не отражались в глазу'),
    ('blur', r'размыт',
     'снимок размыт', 'держите телефон неподвижно 15–20 см от глаза, коснитесь века на экране для фокуса, '
                      'снимайте при хорошем свете (в темноте камера смазывает)'),
    ('small', r'мало реальных пикселей|слишком мелкая|снимите ближе',
     'глаз слишком мелкий в кадре: мало пикселей на веке',
     'поднесите камеру ближе, чтобы глаз занимал большую часть кадра; пришлите оригинал, не пересланное фото'),
    ('no_eye', r'глаз не найден',
     'в кадре не найден глаз', 'снимите один глаз крупным планом: смотрите вверх, нижнее веко оттяните пальцем'),
    ('no_tissue', r'ни конъюнктива, ни склера не найдены|не найдена|анатомическ|не видна',
     'не видно внутренней (розовой) стороны нижнего века',
     'оттяните нижнее веко пальцем вниз, смотрите вверх; веко должно быть видно полосой под глазом'),
    ('cutout', r'вырезанная ткань',
     'это вырезанный фрагмент, а нужен снимок глаза целиком', 'пришлите исходное фото глаза'),
    ('few_px', r'мало чистой ткани',
     'на веке много бликов, теней или ресниц', 'уберите прямой свет, оттяните веко сильнее, ресницы — вне века'),
    ('ood', r'вне диапазона обучающих',
     'цвет снимка не похож на обучающие снимки (необычный свет, фильтр или камера)',
     'переснимите при дневном свете у окна, без фильтров, тёплых ламп и вспышки'),
)
GENERIC = ('other', 'снимок не прошёл проверку', 'переснимите глаз крупным планом при дневном свете')
STAGE_HINT = {'no_eye': 'no_eye', 'no_tissue': 'no_tissue'}


def classify(issue):
    """Строка проблемы → код правила (первое совпавшее) или 'other'."""
    for code, pat, _, _ in RULES:
        if re.search(pat, issue, re.IGNORECASE):
            return code
    return GENERIC[0]


def hints(result):
    """Результат analyze_photo → список {'code', 'because', 'fix'} без повторов (по приоритету RULES).
    Пусто — переснимать не нужно (status 'ok' или нет проблем снимка: например, нет модели)."""
    if result.get('status') == 'ok' or result.get('stage') in ('no_model', 'age'):   # не проблема снимка
        return []
    codes = {classify(x) for x in result.get('issues') or []}
    st = STAGE_HINT.get(result.get('stage'))
    if st:
        codes.add(st)
    if 'no_eye' in codes:                          # глаза нет — подсказки про веко лишние
        codes.discard('no_tissue')
    out = [{'code': c, 'because': b, 'fix': f} for c, _, b, f in RULES if c in codes]
    if not out and result.get('issues'):
        out.append(dict(zip(('code', 'because', 'fix'), GENERIC)))
    return out


def retake_text(result):
    """Одна строка для пользователя: «Переснимите, потому что …. Как: …» или '' (переснимать не нужно)."""
    h = hints(result)
    if not h:
        return ''
    because = '; '.join(x['because'] for x in h)
    fix = ' '.join(f'{i + 1}) {x["fix"]}.' for i, x in enumerate(h)) if len(h) > 1 else h[0]['fix'] + '.'
    return f'Переснимите, потому что {because}. Как: {fix}'
