"""Симуляция другого освещения: для аугментации при обучении и для стресс-теста «другой свет».

Модель: снимок сделан при источнике с цветовой температурой T, а баланс белого камеры остался на D65.
Тогда каждый канал линейного RGB умножается на коэффициент «белого» этого источника (фон Крис).
Это худший случай: телефоны частично компенсируют свет автобалансом.
"""
import numpy as np

from .color import lin_to_srgb, srgb_to_lin

XYZ_TO_LIN_SRGB = np.array([[3.2404542, -1.5371385, -0.4985314],
                            [-0.9692660, 1.8760108, 0.0415560],
                            [0.0556434, -0.2040259, 1.0572252]])


def planck_xy(T):
    """Цветность планковского излучателя (Kim et al. 2002), 1667–25000 K."""
    if not 1667 <= T <= 25000:
        raise ValueError('T вне 1667–25000 K')
    if T <= 4000:
        x = -0.2661239e9 / T ** 3 - 0.2343589e6 / T ** 2 + 0.8776956e3 / T + 0.179910
    else:
        x = -3.0258469e9 / T ** 3 + 2.1070379e6 / T ** 2 + 0.2226347e3 / T + 0.240390
    if T <= 2222:
        y = -1.1063814 * x ** 3 - 1.34811020 * x ** 2 + 2.18555832 * x - 0.20219683
    elif T <= 4000:
        y = -0.9549476 * x ** 3 - 1.37418593 * x ** 2 + 2.09137015 * x - 0.16748867
    else:
        y = 3.0817580 * x ** 3 - 5.87338670 * x ** 2 + 3.75112997 * x - 0.37001483
    return x, y


def kelvin_gains(T, ref=6500):
    """Множители линейных R, G, B для источника T относительно ref (G = 1)."""
    def white(t):
        x, y = planck_xy(t)
        rgb = XYZ_TO_LIN_SRGB @ np.array([x / y, 1.0, (1 - x - y) / y])
        return rgb / rgb[1]
    return (white(T) / white(ref)).astype(np.float32)


def apply_illuminant(rgb, T=6500, exposure=1.0):
    lin = srgb_to_lin(np.clip(rgb, 0, 1)) * kelvin_gains(T) * exposure
    return lin_to_srgb(lin)


def random_relight(rgb, rng):
    """Случайный свет для обучения: T 2700–7500 K (равномерно по 1/T), экспозиция ×0,6–1,6, гамма ±10%."""
    T = 1 / rng.uniform(1 / 7500, 1 / 2700)
    out = apply_illuminant(rgb, T, float(np.exp(rng.uniform(np.log(0.6), np.log(1.6)))))
    return np.clip(out, 0, 1) ** float(np.exp(rng.normal(0, 0.10)))


# Фиксированные условия стресс-теста: 6 температур при нормальной экспозиции + недо- и пересвет
STRESS_CONDITIONS = [(T, 1.0) for T in (2700, 3500, 4500, 5500, 6500, 7500)] + [(6500, 0.6), (6500, 1.5)]
